// Writes apps/web/src/web3/abis.ts from Foundry build output. Run `forge build` first.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const abi = name => JSON.parse(readFileSync(new URL(`out/${name}.sol/${name}.json`, root), 'utf8')).abi;
const target = new URL('../apps/web/src/web3/abis.ts', root);
writeFileSync(target, '/** Generated by contracts/script/export-abis.mjs. Do not edit by hand. */\n'
  + `export const shopAbi = ${JSON.stringify(abi('SlyceShop'))} as const;\n`
  + `export const tournamentAbi = ${JSON.stringify(abi('SlyceTournament'))} as const;\n`
  + `export const arcadeAbi = ${JSON.stringify(abi('SlyceArcade'))} as const;\n`);
console.log('Wrote', target.pathname);
